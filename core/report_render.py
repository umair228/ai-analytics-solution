"""Branded tabular report files: CSV (UTF-8 + BOM), XLSX and PDF (ReportLab).

Input is a plain table (``columns`` + ``rows`` of JSON-safe cells, as the
query executor returns them) plus a :class:`ReportMeta` describing the header
block; output is the file's bytes. The audited dataset export endpoint and the
scheduled email reports both render through here, so a downloaded file and an
emailed one carry the same brand header, "Data as of" stamp and footer.
"""
from __future__ import annotations

import csv
import io
import re
from dataclasses import dataclass, field
from datetime import date, datetime
from zoneinfo import ZoneInfo

from django.conf import settings
from django.utils import timezone
from django.utils.text import slugify

FORMATS = ("csv", "xlsx", "pdf")
CONTENT_TYPES = {
    "csv": "text/csv; charset=utf-8",
    "xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    "pdf": "application/pdf",
}

_BRAND_BLUE = "#0D4D7A"
_GRID_GREY = "#C9D2DC"
_ZEBRA = "#F3F6F9"
_MUTED = "#5B6B7B"


class UnsupportedFormat(ValueError):
    """The requested file format is not one of :data:`FORMATS`."""


@dataclass
class ReportMeta:
    """What a report file says about itself, besides the table."""

    title: str                                   # e.g. the dataset name
    product_name: str = ""                       # brand, from settings
    footer: str = ""                             # brand footer, from settings
    # Ordered (label, value) header lines: "Data as of", "Generated by", ...
    lines: list[tuple[str, str]] = field(default_factory=list)
    data_as_of: str = ""                         # compact stamp for page headers
    generated_by: str = ""
    generated_at: str = ""
    note: str = ""                               # optional narrative paragraph


# ──────────────────────────────────────────────────────────────────────────
#  Time stamps and file names (DIS_REPORT_TZ)
# ──────────────────────────────────────────────────────────────────────────

def report_tz() -> ZoneInfo:
    return ZoneInfo(settings.DIS_REPORT_TZ)


def format_timestamp(dt) -> str:
    """An aware datetime as 'YYYY-MM-DD HH:MM (<DIS_REPORT_TZ>)'."""
    if dt is None:
        return ""
    if timezone.is_naive(dt):
        dt = timezone.make_aware(dt, timezone.get_default_timezone())
    return f"{dt.astimezone(report_tz()):%Y-%m-%d %H:%M} ({settings.DIS_REPORT_TZ})"


def format_stamp(value) -> str:
    """A data-as-of cell (datetime, date or ISO text) as display text.

    Offset-aware values are converted to DIS_REPORT_TZ; naive values are shown
    as stored (the source already recorded them in local time)."""
    if value in (None, ""):
        return ""
    if isinstance(value, datetime):
        parsed = value
    elif isinstance(value, date):
        return value.isoformat()
    else:
        text = str(value).strip()
        try:
            parsed = datetime.fromisoformat(text)
        except ValueError:
            return text
        if len(text) == 10:  # a bare date
            return parsed.date().isoformat()
    if parsed.tzinfo is not None:
        return format_timestamp(parsed)
    return f"{parsed:%Y-%m-%d %H:%M}"


def export_filename(name: str, fmt: str, when=None, fallback: str = "report") -> str:
    """'<slug>-<yyyymmdd>.<ext>', the date taken in DIS_REPORT_TZ."""
    slug = slugify(name or "")[:80].strip("-") or fallback
    day = (when or timezone.now()).astimezone(report_tz())
    return f"{slug}-{day:%Y%m%d}.{fmt}"


# ──────────────────────────────────────────────────────────────────────────
#  Dispatch
# ──────────────────────────────────────────────────────────────────────────

def render(fmt: str, columns, rows, meta: ReportMeta) -> bytes:
    fmt = (fmt or "").lower()
    if fmt == "csv":
        return render_csv(columns, rows, meta)
    if fmt == "xlsx":
        return render_xlsx(columns, rows, meta)
    if fmt == "pdf":
        return render_pdf(columns, rows, meta)
    raise UnsupportedFormat(
        f"Unsupported export format {fmt!r}. Use one of: {', '.join(FORMATS)}.")


def _preamble(meta: ReportMeta) -> list[tuple[str, str]]:
    """The header block shared by CSV and XLSX: brand + title, then the lines."""
    out = [(meta.product_name or "Report", meta.title)]
    out.extend(meta.lines)
    return out


# ──────────────────────────────────────────────────────────────────────────
#  CSV
# ──────────────────────────────────────────────────────────────────────────

# Cells Excel would evaluate as a formula. Negative numbers arrive as real
# numerics, so a leading "-" on text is left alone (matches the query export).
_FORMULA_PREFIXES = ("=", "+", "@", "\t", "\r")


def _csv_cell(value):
    if value is None:
        return ""
    if isinstance(value, str) and value[:1] in _FORMULA_PREFIXES:
        return "'" + value
    return value


def render_csv(columns, rows, meta: ReportMeta) -> bytes:
    """UTF-8 with a BOM (so Excel detects the encoding). The header block is
    '#'-prefixed lines, then a blank line, then the column header and rows —
    tools can skip the block with a comment character (pandas: comment='#')."""
    buf = io.StringIO()
    buf.write("﻿")
    writer = csv.writer(buf)
    for label, value in _preamble(meta):
        writer.writerow([f"# {label}", _csv_cell(value)])
    if meta.footer:
        writer.writerow([f"# {meta.footer}"])
    writer.writerow([])
    writer.writerow([_csv_cell(c) for c in columns])
    for row in rows:
        writer.writerow([_csv_cell(v) for v in row])
    return buf.getvalue().encode("utf-8")


# ──────────────────────────────────────────────────────────────────────────
#  XLSX
# ──────────────────────────────────────────────────────────────────────────

_SHEET_BAD = re.compile(r"[\[\]:*?/\\]")
_XLSX_MAX_CELL = 32767


def _sheet_title(title: str) -> str:
    cleaned = _SHEET_BAD.sub(" ", title or "").strip().strip("'")[:31].strip()
    return cleaned or "Data"


def _text_len(value) -> int:
    return len(_display(value))


def _xlsx_widths(columns, rows, sample=500):
    widths = []
    for i, col in enumerate(columns):
        longest = len(str(col))
        for row in rows[:sample]:
            if i < len(row):
                longest = max(longest, _text_len(row[i]))
        widths.append(min(60, max(8, longest + 2)))
    return widths


def render_xlsx(columns, rows, meta: ReportMeta) -> bytes:
    """One sheet: brand/title + as-of block, then a frozen, auto-filtered table
    with sized columns. Written in openpyxl's streaming mode, so the export
    ceiling (DIS_EXPORT_MAX_ROWS) stays memory-safe."""
    from openpyxl import Workbook
    from openpyxl.cell import WriteOnlyCell
    from openpyxl.cell.cell import ERROR_CODES, ILLEGAL_CHARACTERS_RE
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter
    from openpyxl.worksheet.worksheet import Worksheet

    wb = Workbook(write_only=True)
    ws = wb.create_sheet(_sheet_title(meta.title))
    wb.properties.title = meta.title
    wb.properties.creator = meta.product_name or "Report"

    passthrough = (bool, int, float)

    def clean(v):
        """Numbers/booleans pass through; anything else becomes sheet-safe text."""
        if v is None or v.__class__ in passthrough:
            return v
        text = v if v.__class__ is str else str(v)
        if not text.isprintable():  # cheap pre-check; the regex is the slow path
            text = ILLEGAL_CHARACTERS_RE.sub("", text)
        if len(text) > _XLSX_MAX_CELL:
            text = text[:_XLSX_MAX_CELL - 1] + "…"
        return text

    def as_text(text) -> bool:
        # openpyxl would store "=…" as a live formula and "#N/A" etc. as an
        # error value — data is data, so both are forced to plain text.
        return (text.__class__ is str and text[:1] in ("=", "#")
                and (text[0] == "=" or text in ERROR_CODES))

    def cell(value, font=None, fill=None, align=None):
        c = WriteOnlyCell(ws, value=clean(value))
        if as_text(c.value):
            c.data_type = "s"
        if font is not None:
            c.font = font
        if fill is not None:
            c.fill = fill
        if align is not None:
            c.alignment = align
        return c

    def value_of(v):
        v = clean(v)
        return cell(v) if as_text(v) else v

    preamble = _preamble(meta)
    extra = [meta.footer] if meta.footer else []
    header_row = len(preamble) + len(extra) + 2      # + blank spacer row
    last_row = header_row + len(rows)
    ncols = max(1, len(columns))

    # Column widths and frozen panes must be set before the first row is
    # streamed; the auto-filter / print set-up is written at save time.
    for i, width in enumerate(_xlsx_widths(columns, rows), start=1):
        ws.column_dimensions[get_column_letter(i)].width = width
    ws.column_dimensions["A"].width = max(ws.column_dimensions["A"].width or 0, 18)
    ws.freeze_panes = f"A{header_row + 1}"
    if columns:
        ws.auto_filter.ref = f"A{header_row}:{get_column_letter(ncols)}{last_row}"
    ws.print_title_rows = f"{header_row}:{header_row}"
    ws.page_setup.orientation = "landscape"
    ws.page_setup.paperSize = Worksheet.PAPERSIZE_A4
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.oddHeader.left.text = (meta.product_name or "")[:250]
    ws.oddHeader.right.text = (f"Data as of {meta.data_as_of}" if meta.data_as_of else "")[:250]
    ws.oddFooter.left.text = (meta.footer or "")[:250]
    ws.oddFooter.right.text = "Page &P of &N"

    bold = Font(bold=True)
    top_align = Alignment(vertical="top")
    title_label, title_value = preamble[0]
    ws.append([cell(title_label, font=Font(bold=True, size=13, color=_BRAND_BLUE[1:])),
               cell(title_value, font=Font(bold=True, size=13))])
    for label, value in preamble[1:]:
        ws.append([cell(label, font=bold, align=top_align), value_of(value)])
    for text in extra:
        ws.append([cell(text, font=Font(italic=True, color=_MUTED[1:]))])
    ws.append([])

    head_font = Font(bold=True, color="FFFFFF")
    head_fill = PatternFill("solid", fgColor=_BRAND_BLUE[1:])
    ws.append([cell(str(c), font=head_font, fill=head_fill) for c in columns])
    for row in rows:
        ws.append([value_of(v) for v in row])

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


# ──────────────────────────────────────────────────────────────────────────
#  PDF (ReportLab)
# ──────────────────────────────────────────────────────────────────────────

def _display(value) -> str:
    """Cell text for widths and the PDF (CSV/XLSX keep the raw values)."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        if value != value:  # NaN
            return ""
        if abs(value) >= 1e15 or (0 < abs(value) < 1e-4):
            return f"{value:.6g}"
        text = f"{value:.4f}".rstrip("0").rstrip(".")
        return "0" if text in ("-0", "") else text
    return str(value)


def _is_number(value) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _wrap(text: str, font: str, size: float, width: float, max_lines: int):
    """Greedy word wrap to ``width`` points, splitting over-long tokens (ids,
    URLs) by character. Returns (lines, truncated). Wrapping once here and
    handing the table plain multi-line strings is several times faster than
    ReportLab Paragraphs, which re-wrap on every measure and split."""
    from reportlab.pdfbase.pdfmetrics import stringWidth

    def width_of(s):
        return stringWidth(s, font, size)

    space = width_of(" ")
    lines: list[str] = []
    for raw in text.split("\n"):
        current, current_w = "", 0.0
        for word in raw.split(" "):
            w = width_of(word)
            if w > width:                      # break a long token by character
                if current:
                    lines.append(current)
                    current, current_w = "", 0.0
                chunk = ""
                for ch in word:
                    if chunk and width_of(chunk + ch) > width:
                        lines.append(chunk)
                        chunk = ""
                    chunk += ch
                current, current_w = chunk, width_of(chunk)
                continue
            if not current:
                current, current_w = word, w
            elif current_w + space + w <= width:
                current, current_w = f"{current} {word}", current_w + space + w
            else:
                lines.append(current)
                current, current_w = word, w
        lines.append(current)
        if len(lines) > max_lines:
            break
    if len(lines) > max_lines:
        kept = lines[:max_lines]
        kept[-1] = _fit(kept[-1] + "…", font, size, width)
        return kept, True
    return lines, False


def _fit(text: str, font: str, size: float, width: float) -> str:
    """Trim ``text`` with an ellipsis so it fits ``width`` points."""
    from reportlab.pdfbase.pdfmetrics import stringWidth

    if stringWidth(text, font, size) <= width:
        return text
    while text and stringWidth(text + "…", font, size) > width:
        text = text[:-1]
    return text + "…"


def _pdf_widths(columns, rows, avail, size, pad):
    """Column widths for the printable width ``avail``.

    Each column wants its natural width (header vs 90th-percentile cell) and
    needs at least its longest word (so ids, codes and timestamps never break
    mid-token). When the natural widths do not fit, only the widest columns
    are capped, at a common level (water-filling): free text wraps, short
    columns stay on one line. Spare width is shared out proportionally."""
    from reportlab.pdfbase.pdfmetrics import stringWidth

    def p90(values):
        values = sorted(values)
        return values[min(len(values) - 1, int(len(values) * 0.9))] if values else 0.0

    n = len(columns)
    sample = rows[:300]
    extra = 2 * pad + 2
    natural, floors = [], []
    for i, col in enumerate(columns):
        head = str(col)
        texts = [_display(r[i])[:120] for r in sample if i < len(r)]
        cell_w = p90(stringWidth(t, "Helvetica", size) for t in texts)
        word_w = p90(max((stringWidth(w, "Helvetica", size) for w in t.split()), default=0)
                     for t in texts)
        head_word = max((stringWidth(w, "Helvetica-Bold", size) for w in head.split()),
                        default=0)
        floors.append(min(max(word_w, head_word) + extra, avail * 0.25))
        natural.append(min(max(stringWidth(head, "Helvetica-Bold", size), cell_w) + extra,
                           avail * 0.45))
    natural = [max(nat, flo) for nat, flo in zip(natural, floors)]

    if sum(floors) >= avail:  # too many columns: shrink the floors, words may break
        return [f * avail / sum(floors) for f in floors]
    if sum(natural) <= avail:
        widths = natural
    else:
        lo, hi = 0.0, max(natural)
        for _ in range(40):  # largest common cap that still fits
            cap = (lo + hi) / 2
            if sum(max(f, min(nat, cap)) for nat, f in zip(natural, floors)) <= avail:
                lo = cap
            else:
                hi = cap
        widths = [max(f, min(nat, lo)) for nat, f in zip(natural, floors)]
    total = sum(widths)
    return [w * avail / total for w in widths] if total else [avail / n] * n


def render_pdf(columns, rows, meta: ReportMeta) -> bytes:
    """Landscape A4 table: brand header and footer on every page, the header
    row repeated on each page, wrapped cells and "Page X of Y"."""
    from xml.sax.saxutils import escape

    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.pdfbase.pdfmetrics import stringWidth
    from reportlab.pdfgen import canvas as rl_canvas
    from reportlab.platypus import (
        LongTable, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle,
    )

    page_w, page_h = landscape(A4)
    left = right = 12 * mm
    top, bottom = 20 * mm, 15 * mm
    avail = page_w - left - right
    ncols = len(columns)
    size = 8 if ncols <= 8 else 7 if ncols <= 14 else 6 if ncols <= 22 else 5
    leading = size + 2
    pad = 3.0
    blue, grid, zebra, muted = (colors.HexColor(c) for c in
                                (_BRAND_BLUE, _GRID_GREY, _ZEBRA, _MUTED))

    title_style = ParagraphStyle("title", fontName="Helvetica-Bold", fontSize=14,
                                 leading=18, textColor=blue, spaceAfter=4)
    body_style = ParagraphStyle("body", fontName="Helvetica", fontSize=8.5, leading=11)
    label_style = ParagraphStyle("label", parent=body_style, fontName="Helvetica-Bold")
    note_style = ParagraphStyle("note", parent=body_style, textColor=muted, spaceBefore=4)

    def para(text, style, limit=None):
        text = text if limit is None or len(text) <= limit else text[:limit] + "…"
        return Paragraph(escape(text).replace("\n", "<br/>"), style)

    story = [para(meta.title, title_style)]
    if meta.note:
        story.append(para(meta.note, body_style, limit=2000))
        story.append(Spacer(1, 4))
    if meta.lines:
        info = Table([[para(k, label_style), para(str(v), body_style, limit=1000)]
                      for k, v in meta.lines],
                     colWidths=[38 * mm, avail - 38 * mm], hAlign="LEFT")
        info.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 0),
            ("TOPPADDING", (0, 0), (-1, -1), 1),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
        ]))
        story.append(info)
    story.append(Spacer(1, 6))

    truncated = False
    if not columns:
        story.append(para("No data.", body_style))
    elif not rows:
        story.append(para("No rows.", body_style))
    else:
        widths = _pdf_widths(columns, rows, avail, size, pad)
        inner = [w - 2 * pad - 1 for w in widths]
        numeric = []
        for i in range(ncols):
            values = [r[i] for r in rows if i < len(r) and r[i] is not None]
            numeric.append(bool(values) and all(_is_number(v) for v in values))
        # Bound every cell to 12 wrapped lines so no single row can outgrow a
        # page (ReportLab cannot split a row across pages); the character cap
        # bounds the wrapping work for huge text values.
        max_lines = 12
        char_caps = [max(24, int(w / (size * 0.4)) * max_lines) for w in inner]

        def body_cell(i, value):
            nonlocal truncated
            text = _display(value)
            cut = len(text) > char_caps[i]
            if cut:
                text = text[:char_caps[i]]
            if not cut and "\n" not in text and \
                    stringWidth(text, "Helvetica", size) <= inner[i]:
                return text  # fits on one line as-is
            lines, more = _wrap(text, "Helvetica", size, inner[i], max_lines)
            if cut and not more:
                lines[-1] = _fit(lines[-1] + "…", "Helvetica", size, inner[i])
            truncated = truncated or cut or more
            return "\n".join(lines)

        data = [["\n".join(_wrap(str(c), "Helvetica-Bold", size, inner[i], 4)[0])
                 for i, c in enumerate(columns)]]
        for row in rows:
            data.append([body_cell(i, row[i] if i < len(row) else None)
                         for i in range(ncols)])
        table = LongTable(data, colWidths=widths, repeatRows=1)
        commands = [
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),
            ("FONTSIZE", (0, 0), (-1, -1), size),
            ("LEADING", (0, 0), (-1, -1), leading),
            ("BACKGROUND", (0, 0), (-1, 0), blue),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, zebra]),
            ("GRID", (0, 0), (-1, -1), 0.25, grid),
            ("LEFTPADDING", (0, 0), (-1, -1), pad),
            ("RIGHTPADDING", (0, 0), (-1, -1), pad),
            ("TOPPADDING", (0, 0), (-1, -1), 1.5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 1.5),
        ]
        commands += [("ALIGN", (i, 1), (i, -1), "RIGHT")
                     for i in range(ncols) if numeric[i]]
        table.setStyle(TableStyle(commands))
        if truncated:
            story.append(para("Some long values are shortened in this PDF; the XLSX "
                              "export carries them in full.", note_style))
            story.append(Spacer(1, 4))
        story.append(table)

    def furniture(canv, page, total):
        canv.saveState()
        y_head = page_h - top + 8 * mm
        canv.setFillColor(blue)
        canv.setFont("Helvetica-Bold", 9)
        brand = _fit(meta.product_name or "", "Helvetica-Bold", 9, avail * 0.35)
        canv.drawString(left, y_head, brand)
        x_title = left + stringWidth(brand, "Helvetica-Bold", 9) + (8 if brand else 0)
        canv.setFillColor(colors.black)
        canv.setFont("Helvetica", 8)
        right_text = f"Data as of {meta.data_as_of}" if meta.data_as_of else ""
        right_w = stringWidth(right_text, "Helvetica", 8)
        canv.drawString(x_title, y_head,
                        _fit(meta.title, "Helvetica", 8,
                             max(20, page_w - right - x_title - right_w - 12)))
        if right_text:
            canv.drawRightString(page_w - right, y_head, right_text)
        canv.setStrokeColor(grid)
        canv.setLineWidth(0.5)
        canv.line(left, y_head - 3, page_w - right, y_head - 3)

        y_foot = bottom - 8 * mm
        canv.line(left, y_foot + 9, page_w - right, y_foot + 9)
        canv.setFillColor(muted)
        canv.setFont("Helvetica", 7)
        page_text = f"Page {page} of {total}"
        canv.drawRightString(page_w - right, y_foot, page_text)
        made = " · ".join(x for x in (
            f"Generated by {meta.generated_by}" if meta.generated_by else "",
            meta.generated_at) if x)
        if made:
            canv.drawCentredString(page_w / 2, y_foot,
                                   _fit(made, "Helvetica", 7, avail * 0.4))
        if meta.footer:
            canv.drawString(left, y_foot, _fit(meta.footer, "Helvetica", 7, avail * 0.28))
        canv.restoreState()

    class NumberedCanvas(rl_canvas.Canvas):
        """Defers page furniture until the page count is known (Page X of Y)."""

        def __init__(self, *args, **kwargs):
            super().__init__(*args, **kwargs)
            self._page_states = []

        def showPage(self):  # noqa: N802 — ReportLab API
            self._page_states.append(dict(self.__dict__))
            self._startPage()

        def save(self):
            total = len(self._page_states)
            for state in self._page_states:
                self.__dict__.update(state)
                furniture(self, self._pageNumber, total)
                super().showPage()
            super().save()

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=(page_w, page_h),
        leftMargin=left, rightMargin=right, topMargin=top, bottomMargin=bottom,
        title=meta.title, author=meta.product_name, creator=meta.product_name,
        subject=meta.title,
    )
    doc.build(story, canvasmaker=NumberedCanvas)
    return buf.getvalue()
